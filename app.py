HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
}

pushed_today = set()
today_str = date.today().strftime("%Y-%m-%d")

def main():
    global pushed_today, today_str
    print("\n🎯 v4.0POKEMMO 头目监控正式启动（主线程运行）")
    print("🔔 每分钟检测一次 | 推送和本地完全一致")
    
    while True:
        try:
            # 日期切换重置
            current_day = date.today().strftime("%Y-%m-%d")
            if current_day != today_str:
                today_str = current_day
                pushed_today.clear()
                print("\n📅 新日期，已清空推送记录")

            # 请求数据（和本地一模一样的逻辑）
            response = requests.post(API_URL, headers=HEADERS, timeout=10)
            data = response.json()

            if not data.get("data"):
                now = datetime.now().strftime("%H:%M:%S")
                print(f"[{now}] 暂无头目，继续监控...")
                time.sleep(60)
                continue

            # 遍历头目
            for boss in data["data"]:
                monster_id = boss["monster_id"]
                pokedex_num = monster_id // 100
                pokemon_name = POKEDEX.get(pokedex_num, f"未知精灵({pokedex_num})")
                location = boss["location_id"]
                unique_id = f"{pokemon_name}-{location}"

                move1 = boss.get("move1", "")
                move2 = boss.get("move2", "")
                move3 = boss.get("move3", "")
                move4 = boss.get("move4", "")
                moves = [m for m in [move1, move2, move3, move4] if m]
                moves_str = "、".join(moves) if moves else "无"

                start_h = str(boss["start_hour"]).zfill(2)
                start_m = str(boss["start_minute"]).zfill(2)
                end_h = str(boss["end_hour"]).zfill(2)
                end_m = str(boss["end_minute"]).zfill(2)
                start_time_str = f"{start_h}:{start_m}"
                end_time_str = f"{end_h}:{end_m}"
                description = boss.get("description", "无描述")

                output = (
                    f"🐉 v4.0精灵名称: {pokemon_name}\n"
                    f"📍 位置: {location}\n"
                    f"⚔️ 招式: {moves_str}\n"
                    f"📝 描述: {description}\n"
                    f"⏰ 开始时间: {start_time_str}\n"
                    f"⏱️ 结束时间: {end_time_str}"
                )

                print("="*70)
                print(output)
                print("="*70)

                # 推送逻辑（和本地完全一致）
                if unique_id not in pushed_today:
                    requests.get(MIAO_URL, params={"id": MIAO_ID, "text": output}, timeout=10)
                    pushed_today.add(unique_id)
                    print(f"✅ 已推送喵提醒：{pokemon_name}")

            time.sleep(60)

        except Exception as e:
            print(f"❌ 异常：{str(e)}")
            time.sleep(60)

# -------------------------- 启动主线程（监控脚本） --------------------------
if __name__ == "__main__":
    main()

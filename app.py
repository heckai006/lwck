# 接口配置
API_URL = "https://pokemmo.lanbizi.com/api/alpha/spawn/current"
MIAO_URL = "http://miaotixing.com/trigger"
MIAO_ID = "tb1mrXT"
HEADERS = {"User-Agent":"Mozilla/5.0"}

pushed_today = set()
today_str = date.today().strftime("%Y-%m-%d")

# 监控主逻辑
def monitor_main():
    global pushed_today, today_str
    print("✅ 完整图鉴加载完毕，监控服务启动")
    while True:
        try:
            curr_day = date.today().strftime("%Y-%m-%d")
            if curr_day != today_str:
                today_str = curr_day
                pushed_today.clear()

            res = requests.post(API_URL, headers=HEADERS, timeout=10, verify=False)
            data = res.json()
            if not data.get("data"):
                print(f"[{datetime.now().strftime('%H:%M:%S')}] 暂无头目")
                time.sleep(60)
                continue

            for boss in data["data"]:
                pid = boss["monster_id"] // 100
                name = POKEDEX.get(pid, f"未知{pid}")
                loc = boss["location_id"]
                unique_id = f"{name}_{loc}"

                moves = [boss.get(f"move{i}") for i in range(1,5)]
                moves = [m for m in moves if m]
                move_txt = "、".join(moves) if moves else "无"
                st = f"{boss['start_hour']:02d}:{boss['start_minute']:02d}"
                et = f"{boss['end_hour']:02d}:{boss['end_minute']:02d}"
                desc = boss.get("description","无备注")

                msg = f"【v8.0头目】{name}\n地点：{loc}\n技能：{move_txt}\n时段：{st}-{et}\n说明：{desc}"
                print("-"*50)
                print(msg)
                print("-"*50)

                if unique_id not in pushed_today:
                    requests.get(MIAO_URL, params={"id":MIAO_ID,"text":msg}, timeout=5)
                    pushed_today.add(unique_id)
                    print(f"✅ {name}推送完成")
            time.sleep(60)
        except Exception as e:
            print(f"异常：{e}")
            time.sleep(60)

if __name__ == "__main__":
    threading.Thread(target=run_web_server, daemon=True).start()
    time.sleep(2)
    monitor_main()
